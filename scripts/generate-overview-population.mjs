import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { rolldown } from 'rolldown';
const temporary=await mkdtemp(join(tmpdir(),'sim-overview-population-'));
try {
  const file=join(temporary,'integrate.mjs');
  const bundle=await rolldown({input:resolve('src/universe/galaxy/overviewPopulation.ts'),platform:'node'});
  await bundle.write({file,format:'esm',codeSplitting:false});await bundle.close();
  const {integrateOverviewPopulation,compressOverviewPopulation,overviewThinCount}=await import(pathToFileURL(file).href);
  const base=integrateOverviewPopulation(256,8),refined=integrateOverviewPopulation(512,8);
  if(base.expectedRgb.some((v,c)=>Math.abs(v/refined.expectedRgb[c]-1)>.001)
    || Math.abs(base.cutoffOptical/refined.cutoffOptical-1)>.01)throw Error('Overview source refinement has not converged');
  const data={count:refined.count,parentCount:overviewThinCount(),expectedRgb:refined.expectedRgb,cutoffOptical:refined.cutoffOptical,bins:compressOverviewPopulation(refined)};
  await writeFile('src/universe/galaxy/overviewPopulationTable.ts',`/** Generated by node scripts/generate-overview-population.mjs.\n * 512 mass bins / eight-point phase-aware quadrature, compressed into\n * 1024 equal-number RGB means. Do not tune these for display brightness. */\nexport const overviewPopulationTable = ${JSON.stringify(data)} as const;\n`);
  console.log(JSON.stringify({count:data.count,parentCount:data.parentCount,cutoff:data.cutoffOptical,rgb:data.expectedRgb,bins:data.bins.length},null,2));
} finally {await rm(temporary,{recursive:true,force:true});}
