import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { rolldown } from 'rolldown';
const temporary = await mkdtemp(join(tmpdir(),'sim-field-population-'));
try {
  const output = join(temporary,'integrate.mjs');
  const bundle = await rolldown({input:resolve('src/universe/galaxy/fieldPopulation.ts'),platform:'node'});
  await bundle.write({file:output,format:'esm',codeSplitting:false}); await bundle.close();
  const {integrateFieldPopulation} = await import(pathToFileURL(output).href);
  const table = {};
  for (const component of ['thin-disk','thick-disk','halo','bulge']) {
    const base = integrateFieldPopulation(component,64);
    const refined = integrateFieldPopulation(component,256);
    const a = [base.massSolar,base.luminositySolar,...base.opticalRgbSolar];
    const b = [refined.massSolar,refined.luminositySolar,...refined.opticalRgbSolar];
    const error = Math.max(...a.map((v,i)=>Math.abs(v/b[i]-1)));
    console.log(JSON.stringify({component,error,moments:refined}));
    if (error>2e-6) throw new Error('Field moments did not converge; output left unchanged.');
    table[component] = refined;
  }
  await writeFile('src/universe/galaxy/fieldPopulationTable.ts',`/** Generated by scripts/generate-field-population.mjs. Full primary +\n * coeval companion mass/light per individual field object, including the\n * .013-M☉ clamp atom. Do not tune this table for display brightness. */\nexport const fieldPopulationTable = ${JSON.stringify(table,null,2)} as const;\n`);
} finally { await rm(temporary,{recursive:true,force:true}); }
