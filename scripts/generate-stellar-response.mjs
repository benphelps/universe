import { mkdtemp,rm,writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join,resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { rolldown } from 'rolldown';
const temporary=await mkdtemp(join(tmpdir(),'sim-stellar-response-'));
try {
  const file=join(temporary,'response.mjs'),bundle=await rolldown({input:resolve('src/core/color/optical.ts'),platform:'node'});
  await bundle.write({file,format:'esm',codeSplitting:false});await bundle.close();
  const {opticalSample}=await import(pathToFileURL(file).href);
  const count=1024,minLogTemperature=Math.log(100),logStep=Math.log(1e7/100)/(count-1);
  const samples=Array.from({length:count+3},(_,i)=>{const s=opticalSample(Math.exp(minLogTemperature+(i-1)*logStep));const power=Math.max(s[3],1e-300);return [s[0]/power,s[1]/power,s[2]/power,Math.log(power)];}).flat();
  // A cubic lies within its Bezier control hull, including between knots.
  // Bound log power before exponentiating; no dense-sampling assumption.
  let maxLogFraction=-Infinity;
  for(let i=0;i<count-1;i++){
    const [p,q,r,s]=[0,1,2,3].map(k=>samples[(i+k)*4+3]);
    maxLogFraction=Math.max(maxLogFraction,q,q+(r-p)/6,r-(s-q)/6,r);
  }
  const maxFraction=Math.exp(maxLogFraction)*(1+1e-12);
  const table={maxFraction,id:'optical-380-780',wavelengthNm:[380,780],minLogTemperature,logStep,count,samples};
  await writeFile('src/core/color/stellarOpticalResponse.ts',`/** Generated by node scripts/generate-stellar-response.mjs.\n * Padded uncompressed spectrum response; no runtime spectral integration. */\nexport const stellarOpticalResponse = ${JSON.stringify(table)} as const;\n`);
} finally {await rm(temporary,{recursive:true,force:true});}
