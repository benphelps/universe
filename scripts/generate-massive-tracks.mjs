import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const source = 'data/reference/geneva-z014-v04.tsv';
const input = await readFile(source, 'utf8');
const tracks = new Map();
for (const line of input.split('\n')) {
  const v = line.trim().split(/\s+/).map(Number);
  if (v.length !== 6 || !v.every(Number.isFinite)) continue;
  const [initial, number, ageYears, mass, logL, logT] = v;
  const rows = tracks.get(initial) ?? [];
  if (number !== rows.length + 1) throw new Error('Unexpected track ordering');
  rows.push([ageYears / 1e9, mass, logL, logT]);
  tracks.set(initial, rows);
}
const masses = [...tracks.keys()];
if (masses.join() !== '9,12,15,20,25,32,40,60,85,120' || [...tracks.values()].some(t => t.length !== 400)) {
  throw new Error('Incomplete or unexpected Geneva grid');
}
// Ages in the app run from the first tabulated ZAMS state, not its small
// positive integration age in the source file.
for (const rows of tracks.values()) {
  const origin = rows[0][0];
  for (const row of rows) row[0] -= origin;
  // The published ages are rounded; late-burning rows can have equal ages
  // but different states. Make those instants right-continuous, using the
  // last published state, rather than inventing a positive duration.
  for (let i = rows.length - 2; i >= 0; i--) {
    if (rows[i][0] === rows[i + 1][0]) rows[i] = [...rows[i + 1]];
  }
}
// A synthetic 8-M☉ endpoint matches the inherited track at the boundary.
// Only 8–9 M☉ uses this bridge; do not label it a published Geneva track.
const bridge = [], reference = tracks.get(9);
const lMs = 1.4 * 8 ** 3.5, rMs = 8 ** 0.57;
const tMs = 80 / lMs + 0.0032, termL = 0.75 * 1.73 * lMs;
const termT = 5772 * (termL ** 0.25 / Math.sqrt(1.15 * rMs));
for (let i = 0; i < 400; i++) {
  const ms = i <= 109;
  const p = ms ? reference[i][0] / reference[109][0]
    : (reference[i][0] - reference[109][0]) / (reference[399][0] - reference[109][0]);
  const age = ms ? tMs * p : tMs * (1 + 0.15 * p);
  const l = ms ? 0.75 * lMs * (1 + 0.73 * p) : termL * 1.8 ** p;
  const t = ms ? 5772 * (l ** 0.25 / Math.sqrt(rMs * (0.85 + 0.3 * p))) : termT * (3600 / termT) ** p;
  bridge.push([age, 8, Math.log10(l), Math.log10(t)]);
}
tracks.set(8, bridge);
masses.unshift(8);
const selected = new Set([0, 84, 109, 189, 279, 369, 399]);
const tolerances = { logL: 0.006, logT: 0.004, massFraction: 0.002 };
function worst(rows, initial, lo, hi) {
  const a = rows[lo], b = rows[hi];
  let index = -1, error = 1;
  if (hi <= lo + 1 || a[0] === b[0]) return -1;
  for (let i = lo + 1; i < hi; i++) {
    const p = (rows[i][0] - a[0]) / (b[0] - a[0]);
    const e = Math.max(Math.abs(rows[i][2] - (a[2] + (b[2] - a[2]) * p)) / tolerances.logL,
      Math.abs(rows[i][3] - (a[3] + (b[3] - a[3]) * p)) / tolerances.logT,
      Math.abs(rows[i][1] - (a[1] + (b[1] - a[1]) * p)) / (initial * tolerances.massFraction));
    if (e > error) { error = e; index = i; }
  }
  return index;
}
// Keep a common set of homologous row numbers across masses. Recheck after
// every pass: adding a knot for one track may alter another track's fit.
let changed = true;
while (changed) {
  changed = false;
  const indices = [...selected].sort((a,b) => a-b);
  for (const initial of masses) for (let k = 1; k < indices.length; k++) {
    const index = worst(tracks.get(initial), initial, indices[k-1], indices[k]);
    if (index >= 0 && !selected.has(index)) { selected.add(index); changed = true; }
  }
}
const indices = [...selected].sort((a,b) => a-b);
const checksum = createHash('sha256').update(input).digest('hex');
let output = `/** Generated by npm run generate:massive from Ekström et al. (2012),\n * VizieR J/A+A/537/A146: Z=0.014, initial v/vcrit=0.4. Ages start at ZAMS.\n * Original data and interpolation limits: data/reference/README.md.\n * Source SHA256: ${checksum}\n * The 8-M☉ row is a synthetic bridge, not a published track. */\n`;
output += `export const MASSIVE_MASSES = ${JSON.stringify(masses)} as const;\n`;
output += `export const MASSIVE_PHASE_ROWS = ${JSON.stringify(indices.map(i=>i+1))} as const;\n`;
output += `export const MASSIVE_MS_INDEX = ${indices.indexOf(109)};\n`;
output += '/** Repeating [age Gyr, current M☉, log10 L☉, log10 Teff K]. */\nexport const MASSIVE_TRACKS = [\n';
for (const mass of masses) {
  output += `  // ${mass} M☉\n  new Float64Array([\n`;
  for (const index of indices) output += '    ' + tracks.get(mass)[index].map(v=>Number(v.toPrecision(12))).join(', ') + ',\n';
  output += '  ]),\n';
}
output += '] as const;\n';
await writeFile('src/universe/star/massiveTrackData.ts', output);
console.log(JSON.stringify({ masses, knots: indices.length, tolerances, sourceSha256: checksum }));
