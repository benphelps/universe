import {mkdtemp,rm,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {rolldown} from 'rolldown';
const temporary=await mkdtemp(join(tmpdir(),'sim-field-selection-'));
try {
  const output=join(temporary,'integrate.mjs');
  const bundle=await rolldown({input:resolve('src/universe/galaxy/fieldSelectionQuadrature.ts'),platform:'node'});
  await bundle.write({file:output,format:'esm',codeSplitting:false});await bundle.close();
  const {integrateFieldSelection,fieldPopulationMoments}=await import(pathToFileURL(output).href);
  const entries=[];
  for(const component of ['thin-disk','thick-disk','halo','bulge']) {
    const start=performance.now();
    const coarse=integrateFieldSelection(component,256,32);
    const refined=integrateFieldSelection(component,512,64);
    const width=97,height=65,mean=[0,0,0];
    for(let row=0;row<4;row++)for(let c=0;c<3;c++)mean[c]+=refined.data[((row*height+64)*width+96)*3+c];
    let error=0;
    for(let i=0;i<refined.data.length;i++)error=Math.max(error,Math.abs(refined.data[i]-coarse.data[i])/mean[i%3]);
    console.log(JSON.stringify({component,ms:performance.now()-start,nodes:refined.nodes,mean,maxCdfDifferenceFractionOfFull:error}));
    const correction=Math.max(...mean.map((v,c)=>Math.abs(v/fieldPopulationMoments(component).opticalRgbSolar[c]-1)));
    if(error>.01 || correction>.001)throw Error(`Unconverged field selection for ${component}: CDF ${error}, full ${correction}`);
    entries.push(Float32Array.from(refined.data));
  }
  const all=new Float32Array(entries.reduce((n,v)=>n+v.length,0));
  let offset=0;for(const part of entries){all.set(part,offset);offset+=part.length;}
  await writeFile('src/universe/galaxy/fieldSelectionData.ts',`/** Generated by scripts/generate-field-selection.mjs: 512 mass intervals,\n * 64 companion-ratio samples, phase/age-bin boundaries, eight-point ages.\n * Float32 little-endian cumulative RGB per individual field object. */\nexport const FIELD_SELECTION_DATA = '${Buffer.from(all.buffer).toString('base64')}';\n`);
} finally {await rm(temporary,{recursive:true,force:true});}
