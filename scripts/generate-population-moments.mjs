import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { rolldown } from 'rolldown';

const temporary = await mkdtemp(join(tmpdir(), 'sim-population-moments-'));
try {
  const output = join(temporary, 'integrate.mjs');
  const bundle = await rolldown({ input: resolve('src/universe/galaxy/populationMoments.ts'), platform: 'node' });
  await bundle.write({ file: output, format: 'esm', codeSplitting: false });
  await bundle.close();
  const { integratePopulationMoments, populationMassBounds } = await import(pathToFileURL(output).href);
  const table = {};
  for (const component of ['thin-disk', 'thick-disk', 'halo', 'bulge', 'nuclear-young']) {
    const base = integratePopulationMoments(component, 64);
    const refined = integratePopulationMoments(component, 256);
    if (Math.abs(base.massSolar / refined.massSolar - 1) > 1e-8
      || Math.abs(base.luminositySolar / refined.luminositySolar - 1) > 2e-6
      || base.opticalRgbSolar.some((v, c) => Math.abs(v / refined.opticalRgbSolar[c] - 1) > 2e-6)) {
      throw new Error(`Population quadrature has not converged for ${component}; table left unchanged.`);
    }
    table[component] = refined;
  }
  const text = `/** Generated by npm run generate:population from the full IMF, component\n * age laws and stellar evolution tracks at 256 mass bins. Do not tune these\n * values for display brightness. populationMoments.test.ts checks the model. */\nexport const populationMomentTable = ${JSON.stringify(table, null, 2)} as const;\n`;
  await writeFile('src/universe/galaxy/populationMomentTable.ts', text);
  const nuclearBounds = ['thick-disk', 'nuclear-young'].map(component => populationMassBounds(component, 256));
  await writeFile('src/universe/galaxy/nuclearMassBounds.ts', `/** Generated by npm run generate:population. IMF-probability intervals\n * at 256 base mass bins, split where phases enter/leave the old and young\n * nuclear age windows. Keep expensive track-root searches offline. */\nexport const nuclearMassBounds = ${JSON.stringify(nuclearBounds)} as const;\n`);
  console.log('Updated the seed-independent population moments; 64/256-bin convergence passed.');
} finally {
  await rm(temporary, { recursive: true, force: true });
}
